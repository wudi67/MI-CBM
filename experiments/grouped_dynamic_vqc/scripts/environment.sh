#!/usr/bin/env bash
set -euo pipefail
GROUPED_VQC_ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)
VQC_PREFIX=${VQC_PREFIX:-/root/miniforge3/envs/VQC}
VQC_PYTHON=${VQC_PYTHON:-$VQC_PREFIX/bin/python}
export CONDA_PREFIX="$VQC_PREFIX"
export PATH="$VQC_PREFIX/bin:$PATH"
export LD_LIBRARY_PATH="$VQC_PREFIX/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
export PYTHONPATH="$GROUPED_VQC_ROOT${PYTHONPATH:+:$PYTHONPATH}"
export OMP_NUM_THREADS=1 MKL_NUM_THREADS=1 CUBLAS_WORKSPACE_CONFIG=:4096:8
export PYTHONUNBUFFERED=1 COLORTERM=truecolor
unset NO_COLOR
cd "$GROUPED_VQC_ROOT"
